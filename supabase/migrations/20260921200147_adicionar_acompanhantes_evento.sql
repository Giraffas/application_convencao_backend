create table if not exists "GIRAFFAS_PROD"."EV_ACOMPANHANTES" (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  id_pedido text,
  nome_evento text,
  nome text,
  nome_cracha text,
  cpf text,
  email text,
  data_nascimento date,
  telefone text,
  tm_camiseta character varying,
  tm_chinelo character varying,
  participa_auditorio boolean,
  idade_evento integer,
  categoria text,
  valor_individual numeric(12, 2),
  cpf_anfitriao text
);

alter table "GIRAFFAS_PROD"."EV_ACOMPANHANTES"
  add column if not exists id_pedido text,
  add column if not exists nome_evento text,
  add column if not exists telefone text;

do $$
begin
  if exists (
    select 1
      from pg_catalog.pg_attribute
     where attrelid = '"GIRAFFAS_PROD"."EV_ACOMPANHANTES"'::regclass
       and attname = 'id'
       and attidentity = ''
  ) then
    alter table "GIRAFFAS_PROD"."EV_ACOMPANHANTES"
      alter column id add generated by default as identity;
  end if;
end
$$;

do $$
begin
  if exists (
